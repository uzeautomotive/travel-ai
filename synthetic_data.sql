-- ---------- 1. Хүснэгтүүд ба анхны өгөгдөл ----------
DROP TABLE IF EXISTS admins, payments, bookings, tours, customers, guides CASCADE;

CREATE TABLE guides (
  guide_id         SERIAL PRIMARY KEY,
  full_name        VARCHAR(100) NOT NULL,
  language         VARCHAR(30),
  experience_years INTEGER CHECK (experience_years >= 0)
);

CREATE TABLE tours (
  tour_id     SERIAL PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  destination VARCHAR(50),
  days        INTEGER CHECK (days > 0),
  price       NUMERIC(12,2) CHECK (price > 0),
  start_date  DATE,
  guide_id    INTEGER REFERENCES guides(guide_id)
);

CREATE TABLE customers (
  customer_id SERIAL PRIMARY KEY,
  full_name   VARCHAR(100) NOT NULL,
  country     VARCHAR(50),
  email       VARCHAR(100)
);

CREATE TABLE bookings (
  booking_id  SERIAL PRIMARY KEY,
  tour_id     INTEGER NOT NULL REFERENCES tours(tour_id),
  customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
  people      INTEGER CHECK (people > 0),
  booked_at   DATE DEFAULT CURRENT_DATE,
  status      VARCHAR(20) DEFAULT 'pending'
);

CREATE TABLE payments (
  payment_id SERIAL PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(booking_id),
  amount     NUMERIC(12,2) CHECK (amount > 0),
  paid_at    DATE,
  method     VARCHAR(20)
);

